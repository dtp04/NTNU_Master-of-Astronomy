e_verify = 0.2
h_test_list = [0.5, 0.2, 0.1, 0.05, 0.02, 0.01, 0.005, 0.002, 0.001]
measured_rates = []
theoretical_rates = []

for h_val in h_test_list:
    sim_v = KeplerLeapfrogProject(e=e_verify, h=h_val, periods=100, ordering='O')
    A_track = sim_v.run_precession()
    angles = np.unwrap(np.arctan2(A_track[:, 1], A_track[:, 0]))
    omega_measured = (angles[-1] - angles[0]) / sim_v.t_max
    measured_rates.append(omega_measured)
    omega_theoretical = - (h_val**2) * (4.0 + e_verify**2) / (16.0 * (1.0 - e_verify**2)**3)
    theoretical_rates.append(omega_theoretical)
    pct_error = abs((omega_measured - omega_theoretical) / omega_theoretical) * 100
    print(f"h = {h_val} | Simulation: {omega_measured:.8e} | Theoretical: {omega_theoretical:.8e} | Error: {pct_error:.8e}%")

plt.figure(figsize=(7, 5))
plt.loglog(h_test_list, np.abs(measured_rates), 'o', label='Simulation')
plt.loglog(h_test_list, np.abs(theoretical_rates), label=r'$\langle\omega\rangle = -h^2 \frac{4+e^2}{16(1-e^2)^3}$')
plt.title(r'Precession rate $\langle\omega\rangle$')
