import numpy as np
import matplotlib.pyplot as plt

class KeplerLeapfrogProject:
    def __init__(self, e=0.2, h=0.01, periods=100, ordering='O'):
        self.e = e
        self.h = h
        self.ordering = ordering
        self.tau = 2.0 * np.pi
        self.t_max = periods * self.tau
        self.steps = int(self.t_max / h)
        self.q = np.array([1.0 - e, 0.0])
        self.p = np.array([0.0, np.sqrt((1.0 + e) / (1.0 - e))])
        self.H0 = -0.5

    def get_acc(self, q):
        denom = (q[0]**2 + q[1]**2)**(1.5)
        return -q / denom

    def compute_H(self, q, p):
        return 0.5 * (p[0]**2 + p[1]**2) - 1.0 / np.sqrt(q[0]**2 + q[1]**2)

    def compute_L(self, q, p):
        return q[0] * p[1] - q[1] * p[0]

    def compute_H2(self, q, p):
        q_dot_p = q[0]*p[0] + q[1]*p[1]
        p_sq = p[0]**2 + p[1]**2
        q_sq = q[0]**2 + q[1]**2
        return (1.0 / 24.0) * (2.0 * (1.0 / (q_sq**2)) - ((p_sq / (q_sq**(1.5))) - (3.0 * (q_dot_p**2) / (q_sq**(2.5)))))

    def step(self):
        if self.ordering == 'O':
            acc_start = self.get_acc(self.q)
            p_half = self.p + (self.h / 2.0) * acc_start
            self.q = self.q + self.h * p_half
            acc_end = self.get_acc(self.q)
            self.p = p_half + (self.h / 2.0) * acc_end
        elif self.ordering == 'O_prime':
            q_half = self.q + (self.h / 2.0) * self.p
            acc_mid = self.get_acc(q_half)
            self.p = self.p + self.h * acc_mid
            self.q = q_half + (self.h / 2.0) * self.p

    def run(self):
        H_history = np.zeros(self.steps)
        H_tilde_history = np.zeros(self.steps)
        L_history = np.zeros(self.steps)
        for i in range(self.steps):
            H_history[i] = self.compute_H(self.q, self.p)
            H2_val = self.compute_H2(self.q, self.p)
            H_tilde_history[i] = H_history[i] + (self.h**2) * H2_val
            L_history[i] = self.compute_L(self.q, self.p)
            self.step()
        return H_history, H_tilde_history, L_history

    def run_trajectory(self):
        q1_history = np.zeros(self.steps)
        q2_history = np.zeros(self.steps)
        for i in range(self.steps):
            q1_history[i] = self.q[0]
            q2_history[i] = self.q[1]
            self.step()
        return q1_history, q2_history

    def compute_A(self, q, p):
        L_z = self.compute_L(q, p)
        r = np.sqrt(q[0]**2 + q[1]**2)
        Ax = p[1] * L_z - q[0] / r
        Ay = -p[0] * L_z - q[1] / r
        return np.array([Ax, Ay])

    def run_precession(self):
        A_history = np.zeros((self.steps, 2))
        for i in range(self.steps):
            A_history[i] = self.compute_A(self.q, self.p)
            self.step()
        return A_history

